#!/usr/bin/env python3
"""Generate the MCP `explain_finding` data from the verified three-state corpus.

Reads demo/juliet/manifest.json + the A/B/C files and emits mcp/src/generated/findings.ts — a
`Record<findingCode, FindingEntry[]>` the kenbi MCP server imports so `explain_finding(code)` can
return, for any finding kenbi emits, the worked A (trigger) / B (why a half-fix stays RED) /
C (fix) example plus its metadata. The corpus is the single source of truth; this generated file
is committed and kept in sync by --check (run in demo/verify_three_state.py), so it can never
drift from the verified files or present wrong code.

Usage:  python3 demo/gen_mcp_from_corpus.py            # write mcp/src/generated/findings.ts
        python3 demo/gen_mcp_from_corpus.py --check     # exit 1 if the committed file is stale
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
JULIET = os.path.join(HERE, "juliet")
GENDIR = os.path.join(ROOT, "mcp", "src", "generated")
OUT = os.path.join(GENDIR, "findings.ts")
CATALOGUE_OUT = os.path.join(GENDIR, "catalogue.ts")
DIRS = {"A": "juliet", "B": "juliet_annotated", "C": "juliet_rewritten"}
AXIS_ORDER = ["ownership", "spatial", "init", "typecheck", "concurrency"]
AXIS_TITLE = {"ownership": "Ownership & lifetime", "spatial": "Spatial (bounds)",
              "init": "Initialisation", "typecheck": "Type confusion",
              "concurrency": "Concurrency (locks / deadlock)"}

# Leading explanatory comments the code snippet does not need (the STATE sentence becomes `why`;
# the CWE line is redundant with the metadata). @-annotations and @mem are KEPT — they are the
# point.
_PROSE = re.compile(r"/\*\s*(?:STATE\b|CWE:).*?\*/\s*", re.DOTALL)
_STATE = re.compile(r"STATE\s+[ABC]\s*[—-]\s*(.*?)\*/", re.DOTALL)


def snippet(state, filename):
    path = os.path.join(HERE, DIRS[state], filename)
    text = open(path).read()
    m = _STATE.search(text)
    why = re.sub(r"\s+", " ", m.group(1)).strip() if m else ""
    code = _PROSE.sub("", text).strip() + "\n"
    return {"code": code, "why": why}


def build():
    entries = json.load(open(os.path.join(JULIET, "manifest.json")))["entries"]
    findings = {}
    for e in entries:
        entry = {
            "id": e["id"], "cwe": e["cwe"], "class": e["class"], "axis": e["axis"],
            "intent": e["intent"], "title": e["title"], "contracts": e["contracts"],
            "provenance": e["provenance"],
            "A": snippet("A", e["file"]), "B": snippet("B", e["file"]),
            "C": snippet("C", e["file"]),
        }
        for code in e["class"]:                     # index by every converged finding code
            findings.setdefault(code, []).append(entry)
    return findings


HEADER = """// AUTO-GENERATED by demo/gen_mcp_from_corpus.py from the verified three-state corpus
// (demo/juliet/manifest.json + the A/B/C files). DO NOT EDIT — run the generator to refresh.
// demo/verify_three_state.py --check-generated fails if this file drifts from the corpus.

export interface StateSnippet { code: string; why: string; }
export interface Provenance { cve: string; project: string; fixCommit: string; url: string; note?: string; }
export interface FindingEntry {
  id: string; cwe: string; class: string[]; axis: string; intent: string;
  title: string; contracts: string[]; provenance: Provenance | null;
  A: StateSnippet; B: StateSnippet; C: StateSnippet;
}

// findingCode -> the worked examples whose state B converges onto it.
export const FINDINGS: Record<string, FindingEntry[]> =
"""


def render():
    return HEADER + json.dumps(build(), indent=2, ensure_ascii=False) + ";\n"


CAT_HEADER = """// AUTO-GENERATED by demo/gen_mcp_from_corpus.py — DO NOT EDIT. The complete-class-coverage
// section of the kenbi://patterns resource, one safe (state C) shape per corpus entry.
export const CATALOGUE: string =
"""

CAT_INTRO = (
    "## Complete coverage, indexed by intent (generated from the verified corpus)\n\n"
    "What you are trying to DO, grouped by axis, each with the safe shape (state C) that passes and "
    "the class it prevents — so you can look up a shape BEFORE writing. For the full A (trigger) / "
    "B (why a half-fix stays RED) / C (fix) worked example of a finding you already hit, call the "
    "`explain_finding` tool with its code. Generated from the three-state corpus, so it can never "
    "drift or show wrong code.\n"
)


def build_catalogue():
    entries = json.load(open(os.path.join(JULIET, "manifest.json")))["entries"]
    by_axis = {}
    for e in entries:
        by_axis.setdefault(e["axis"], []).append(e)
    parts = [CAT_INTRO]
    for ax in AXIS_ORDER:
        if ax not in by_axis:
            continue
        parts.append("### " + AXIS_TITLE[ax] + "\n")
        for e in sorted(by_axis[ax], key=lambda e: e["intent"]):
            c = snippet("C", e["file"])
            cls = " / ".join("`%s`" % x for x in e["class"])
            contracts = ", ".join(e["contracts"]) or "none"
            intent = e["intent"][:1].upper() + e["intent"][1:]     # lead with the intent
            prov = ("  _(real: %s)_" % e["provenance"]["cve"]) if e["provenance"] else ""
            lang = "cpp" if e["file"].endswith(".cpp") else "c"
            parts.append(
                "**%s** — prevents %s · %s · %s%s\n```%s\n%s```\n"
                % (intent, cls, e["cwe"], contracts, prov, lang, c["code"]))
    return "\n".join(parts)


def render_catalogue():
    return CAT_HEADER + json.dumps(build_catalogue(), ensure_ascii=False) + ";\n"


TARGETS = [(OUT, render), (CATALOGUE_OUT, render_catalogue)]


def main():
    if "--check" in sys.argv:
        stale = False
        for path, fn in TARGETS:
            cur = open(path).read() if os.path.exists(path) else ""
            if cur != fn():
                print("STALE: %s is out of sync — run demo/gen_mcp_from_corpus.py" % path); stale = True
        if stale:
            sys.exit(1)
        print("generated MCP files are in sync")
        return
    os.makedirs(GENDIR, exist_ok=True)
    for path, fn in TARGETS:
        open(path, "w").write(fn())
    n = sum(len(v) for v in build().values())
    print("wrote findings.ts (%d codes, %d entry-refs) + catalogue.ts" % (len(build()), n))


if __name__ == "__main__":
    main()
